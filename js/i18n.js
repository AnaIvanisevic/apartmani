const KEY = "dorana-lang";

export function getLang() {
  const q = new URLSearchParams(location.search).get("lang");
  if (q && T[q]) { try { localStorage.setItem(KEY, q); } catch (e) {} return q; }
  try { const s = localStorage.getItem(KEY); if (s && T[s]) return s; } catch (e) {}
  const nav = (navigator.language || "hr").slice(0, 2).toLowerCase();
  return T[nav] ? nav : "en";
}

export function setLang(l) {
  try { localStorage.setItem(KEY, l); } catch (e) {}
  const u = new URL(location.href);
  u.searchParams.set("lang", l);
  history.replaceState(null, "", u);
}

export function t(key, lang) {
  return (T[lang] && T[lang][key]) ?? T.en[key] ?? T.hr[key] ?? key;
}

export function applyI18n(lang, root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n, lang); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh, lang); });
}
